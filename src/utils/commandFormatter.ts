const arrowMap: { [key: string]: string } = {
  '236236': '↓↘→↓↘→',
  '214214': '↓↙←↓↙←',
  '623': '→↓↘',
  '421': '←↓↙',
  '236': '↓↘→',
  '214': '↓↙←',
  '41236': '←↙↓↘→',
  '63214': '→↘↓↙←',
  '2タメ8': '［↓］↑',
  '4タメ6': '［←］→',
  '1タメ6': '［↙］→',
  '1タメ3': '［↙］↘',
  '2 + ': '↓ + ',
  '6 + ': '→ + ',
  '4 + ': '← + ',
  '8 + ': '↑ + ',
  '1 + ': '↙ + ',
  '3 + ': '↘ + ',
  '7 + ': '↖ + ',
  '9 + ': '↗ + ',
  '2+': '↓+',
  '6+': '→+',
  '4+': '←+',
  '8+': '↑+',
  '1+': '↙+',
  '3+': '↘+',
  '7+': '↖+',
  '9+': '↗+',
};

export const formatCommandToArrows = (text: string): string => {
  if (!text) return '';
  let result = text;

  // 複合コマンド（長いものから順に置換）
  Object.keys(arrowMap).forEach((key) => {
    result = result.split(key).join(arrowMap[key]);
  });

  // 単独の方向数字（例: 2弱P -> ↓弱P, 5強P -> 立強P, 6強 -> →強）
  result = result
    .replace(/(^|[\s>])5([弱中強])/g, '$1立$2')
    .replace(/(^|[\s>])2([弱中強])/g, '$1↓$2')
    .replace(/(^|[\s>])6([弱中強])/g, '$1→$2')
    .replace(/(^|[\s>])4([弱中強])/g, '$1←$2')
    .replace(/(^|[\s>])8([弱中強])/g, '$1↑$2')
    .replace(/(^|[\s>])3([弱中強])/g, '$1↘$2')
    .replace(/(^|[\s>])1([弱中強])/g, '$1↙$2')
    .replace(/(^|[\s>])9([弱中強])/g, '$1↗$2')
    .replace(/(^|[\s>])7([弱中強])/g, '$1↖$2');

  return result;
};
