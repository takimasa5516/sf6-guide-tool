export const getMatchupAdviceForPair = (
  playerChar: Character,
  opponentChar: Character
): MatchupAdvice => {
  // 1. 手動で設定された個別対戦データがあれば最優先で採用
  const custom = playerChar.matchups?.find((m) => m.opponentId === opponentChar.id);
  if (custom) {
    return custom;
  }

  // 2. 相手キャラのプロファイルデータを取得（未定義時はフォールバック）
  const oppData = OPPONENT_DATA[opponentChar.id] || {
    threats: [`相手の主力技「${opponentChar.keyMoves[0]?.name || '必殺技'}」のリーチと突進に注意`, '中距離でのキャンセルドライブラッシュ'],
    tips: ['相手の攻撃が届かない間合いをキープし、技の空振りに差し返す', 'ダウンを奪ったら強気に攻め立ててペースを握る'],
    punishes: [
      { move: `${opponentChar.keyMoves[0]?.name || '無敵技'} ガード後`, frame: '-30F以上', tip: '最大パニカンコンボ' },
    ],
  };

  // 3. アーキタイプによる相性目安の自動判定
  let advantageLevel: '有利' | '微有利' | '五分' | '微不利' | '不利' = '五分';
  const pArch = playerChar.archetype;
  const oArch = opponentChar.archetype;

  if (pArch.includes('道着') || pArch.includes('スタンダード')) {
    if (oArch.includes('コマンド投げ')) advantageLevel = '微有利';
    else if (oArch.includes('リーチ')) advantageLevel = '微不利';
  } else if (pArch.includes('コマンド投げ')) {
    if (oArch.includes('リーチ') || oArch.includes('設置')) advantageLevel = '微不利';
    else if (oArch.includes('インファイター')) advantageLevel = '微有利';
  } else if (pArch.includes('リーチ')) {
    if (oArch.includes('コマンド投げ')) advantageLevel = '有利';
    else if (oArch.includes('スピード')) advantageLevel = '五分';
  }

  // 4. 自キャラの強みを活かした実践アドバイスの動的構築
  const combinedTips = [
    ...oppData.tips,
    `${playerChar.name}の得意技「${playerChar.keyMoves[0]?.name || '主力技'}」で相手を牽制し、ペースを握る`,
  ];

  // 5. 確反リストの生成
  const punishList: PunishPoint[] = oppData.punishes.map((p) => ({
    opponentMove: p.move,
    frameAdvantage: p.frame,
    recommendedPunish: p.tip.includes('最大')
      ? `${playerChar.name}のパニカン最大コンボ（${playerChar.combos.find(c => c.category.includes('パニカン'))?.classicRecipe || '強攻撃始動'}）`
      : `${playerChar.name}の最速小技コンボ（${playerChar.combos[0]?.classicRecipe || '小技刻み'}）`,
    note: p.tip,
  }));

  return {
    opponentId: opponentChar.id,
    opponentName: opponentChar.name,
    advantageLevel,
    coreStrategy: `${playerChar.name}の${pArch}としての強みを活かし、${opponentChar.name}の得意間合い（${oArch}）を封じる戦術をとる。相手の危険技を的確に拒否し、スキの大きい技には最大反撃を叩き込む。`,
    keyThreats: oppData.threats,
    punishList,
    practicalTips: combinedTips,
  };
};
